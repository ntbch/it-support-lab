#!/usr/bin/env bash
# pc-health-check.sh — Instant Workstation Diagnostic Collector for IT Helpdesk
# Collects hardware specs, OS health, disk space, top processes, and network connectivity.
# Generates a clean Markdown report to attach to support tickets.
#
# Usage:
#   ./pc-health-check.sh [output_file.md]

set -u

OUTPUT_FILE="${1:-diagnostic-report-$(date +%Y%m%d-%H%M%S).md}"

echo "Collecting system diagnostics..."

# 1. System & OS
HOSTNAME=$(hostname 2>/dev/null || uname -n)
KERNEL=$(uname -r)
UPTIME=$(uptime -p 2>/dev/null || uptime | awk -F'( |,|:)+' '{if ($7=="min") m=$6; else {if ($7~/^day/) {d=$6;h=$8;m=$9} else {h=$6;m=$7}}} {print d+0,"days,",h+0,"hours,",m+0,"min"}')

OS_NAME="Linux"
if [ -f /etc/os-release ]; then
  # shellcheck source=/dev/null
  OS_NAME=$(grep -E '^PRETTY_NAME=' /etc/os-release | cut -d= -f2 | tr -d '"')
fi

# 2. CPU & Memory
CPU_MODEL=$(grep -m1 'model name' /proc/cpuinfo 2>/dev/null | cut -d: -f2 | sed 's/^[ \t]*//' || uname -m)
CPU_CORES=$(grep -c '^processor' /proc/cpuinfo 2>/dev/null || echo "1")
LOAD_AVG=$(cat /proc/loadavg 2>/dev/null | awk '{print $1", "$2", "$3}' || echo "N/A")

MEM_TOTAL=$(free -h 2>/dev/null | awk '/^Mem:/ {print $2}')
MEM_USED=$(free -h 2>/dev/null | awk '/^Mem:/ {print $3}')
MEM_AVAIL=$(free -h 2>/dev/null | awk '/^Mem:/ {print $7}')

# 3. Disk Space (Root partition)
DISK_USAGE=$(df -h / 2>/dev/null | awk 'NR==2 {print $3 " used / " $2 " total (" $5 " used)"}')

# 4. Network
DEFAULT_GW=$(ip route 2>/dev/null | awk '/^default/ {print $3; exit}')
PRIMARY_IP=$(ip -4 addr show scope global 2>/dev/null | awk '/inet / {print $2; exit}')
IP_STATUS="Assigned"
case "$PRIMARY_IP" in
  "") PRIMARY_IP="none"; IP_STATUS="MISSING (no IPv4 address)" ;;
  169.254.*) IP_STATUS="APIPA (no DHCP lease)" ;;
esac
[ -n "$DEFAULT_GW" ] || DEFAULT_GW="None"

# Ping test (1 packet to gateway, 1 to 8.8.8.8)
GW_PING="FAIL"
if [ "$DEFAULT_GW" != "None" ] && ping -c 1 -W 2 "$DEFAULT_GW" >/dev/null 2>&1; then
  GW_PING="PASS"
fi

INET_PING="FAIL"
if ping -c 1 -W 2 8.8.8.8 >/dev/null 2>&1; then
  INET_PING="PASS"
fi

DNS_TEST="FAIL"
if host google.com >/dev/null 2>&1 || getent hosts google.com >/dev/null 2>&1; then
  DNS_TEST="PASS"
fi

# 5. Top 5 Processes by Memory
TOP_MEM_PROCS=$(ps -eo pid,ppid,%cpu,%mem,comm --sort=-%mem 2>/dev/null | head -n 6)

# 6. Top 5 Processes by CPU
TOP_CPU_PROCS=$(ps -eo pid,ppid,%cpu,%mem,comm --sort=-%cpu 2>/dev/null | head -n 6)

# Generate Markdown Report
cat << EOF > "$OUTPUT_FILE"
# Workstation Diagnostic Report

**Generated:** $(date -u +"%Y-%m-%d %H:%M:%S UTC")  
**Host:** $HOSTNAME  
**OS:** $OS_NAME (Kernel: $KERNEL)  
**Uptime:** $UPTIME  

---

## 1. Hardware & Resource Utilization

| Component | Metric | Status |
|---|---|---|
| **CPU** | $CPU_MODEL ($CPU_CORES cores) | Load Average: $LOAD_AVG |
| **Memory** | $MEM_USED / $MEM_TOTAL (Available: $MEM_AVAIL) | Healthy |
| **Root Disk** | $DISK_USAGE | Monitored |

---

## 2. Network Connectivity Diagnostics

| Test Target | Target Address | Result |
|---|---|---|
| **Local IP** | $PRIMARY_IP | $IP_STATUS |
| **Default Gateway** | $DEFAULT_GW | $GW_PING |
| **Internet Access (8.8.8.8)** | 8.8.8.8 | $INET_PING |
| **DNS Name Resolution** | google.com | $DNS_TEST |

---

## 3. Process Health Analysis

### Top 5 Processes by Memory Usage
\`\`\`text
$TOP_MEM_PROCS
\`\`\`

### Top 5 Processes by CPU Usage
\`\`\`text
$TOP_CPU_PROCS
\`\`\`

---
*Report generated by IT Support Diagnostic Toolkit (pc-health-check.sh)*
EOF

echo "Diagnostic report successfully written to: $OUTPUT_FILE"
