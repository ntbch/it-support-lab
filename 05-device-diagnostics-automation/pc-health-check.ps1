# pc-health-check.ps1 — Windows Workstation Diagnostic Collector for IT Helpdesk
# Collects hardware specs, OS health, disk space, top processes, and network connectivity.
# Generates a clean Markdown report to attach to support tickets.
#
# Usage:
#   .\pc-health-check.ps1 [-OutputFile "diagnostic-report.md"]

param(
    [string]$OutputFile = "diagnostic-report-$((Get-Date).ToString('yyyyMMdd-HHmmss')).md"
)

$ErrorActionPreference = "SilentlyContinue"

Write-Host "Collecting Windows system diagnostics..."

# 1. System & OS
$cs = Get-CimInstance Win32_ComputerSystem
$os = Get-CimInstance Win32_OperatingSystem
$hostName = $cs.DNSHostName
$osName = "$($os.Caption) ($($os.Version))"
$uptime = (Get-Date) - $os.LastBootUpTime
$uptimeFormatted = "$($uptime.Days) days, $($uptime.Hours) hours, $($uptime.Minutes) minutes"

# 2. CPU & Memory
$cpu = Get-CimInstance Win32_Processor | Select-Object -First 1
$totalRamGB = [math]::Round($cs.TotalPhysicalMemory / 1GB, 1)
$freeRamGB = [math]::Round($os.FreePhysicalMemory / 1MB, 1)
$usedRamGB = [math]::Round($totalRamGB - $freeRamGB, 1)

# 3. Disks
$disks = Get-Volume | Where-Object { $_.DriveLetter -ne $null -and $_.DriveType -eq 'Fixed' } | ForEach-Object {
    $sizeGB = [math]::Round($_.Size / 1GB, 1)
    $freeGB = [math]::Round($_.SizeRemaining / 1GB, 1)
    $usedPercent = [math]::Round((($sizeGB - $freeGB) / $sizeGB) * 100, 1)
    "$($_.DriveLetter): $usedPercent% used ($freeGB GB free / $sizeGB GB total)"
}

# 4. Network
$netAdapter = Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway -ne $null } | Select-Object -First 1
$ipAddress = $netAdapter.IPv4Address.IPAddress
$gateway = $netAdapter.IPv4DefaultGateway.NextHop
$dns = ($netAdapter.DNSServer.ServerAddresses -join ", ")

$gwPing = if ($gateway -and (Test-Connection -ComputerName $gateway -Count 1 -Quiet)) { "PASS" } else { "FAIL" }
$inetPing = if (Test-Connection -ComputerName "8.8.8.8" -Count 1 -Quiet) { "PASS" } else { "FAIL" }
$dnsTest = if (Resolve-DnsName -Name "google.com" -ErrorAction SilentlyContinue) { "PASS" } else { "FAIL" }

# 5. Top 5 Processes
$topMem = Get-Process | Sort-Object WorkingSet -Descending | Select-Object -First 5 | Format-Table Id, ProcessName, @{Name="RAM (MB)";Expression={[math]::Round($_.WorkingSet / 1MB, 1)}}, @{Name="CPU (s)";Expression={[math]::Round($_.CPU, 1)}} | Out-String
$topCpu = Get-Process | Where-Object { $_.CPU -gt 0 } | Sort-Object CPU -Descending | Select-Object -First 5 | Format-Table Id, ProcessName, @{Name="CPU (s)";Expression={[math]::Round($_.CPU, 1)}}, @{Name="RAM (MB)";Expression={[math]::Round($_.WorkingSet / 1MB, 1)}} | Out-String

# Generate Report
$report = @"
# Windows Workstation Diagnostic Report

**Generated:** $((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss UTC'))  
**Host:** $hostName  
**OS:** $osName  
**Uptime:** $uptimeFormatted  

---

## 1. Hardware & Resource Utilization

| Component | Metric | Status |
|---|---|---|
| **CPU** | $($cpu.Name) ($($cpu.NumberOfCores) cores / $($cpu.NumberOfLogicalProcessors) threads) | Monitored |
| **Memory** | $usedRamGB GB used / $totalRamGB GB total (Free: $freeRamGB GB) | Healthy |
| **Disks** | $($disks -join "<br>") | Checked |

---

## 2. Network Connectivity Diagnostics

| Test Target | Target Address | Result |
|---|---|---|
| **Local IP** | $ipAddress | Assigned |
| **Default Gateway** | $gateway | $gwPing |
| **Internet Access (8.8.8.8)** | 8.8.8.8 | $inetPing |
| **DNS Name Resolution** | google.com ($dns) | $dnsTest |

---

## 3. Process Health Analysis

### Top 5 Processes by Memory Usage
``````text
$topMem
``````

### Top 5 Processes by CPU Time
``````text
$topCpu
``````

---
*Report generated by IT Support Diagnostic Toolkit (pc-health-check.ps1)*
"@

Set-Content -Path $OutputFile -Value $report -Encoding UTF8
Write-Host "Diagnostic report successfully written to: $OutputFile"
